package session

import (
	"crypto/sha256"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"net/url"
	"strconv"
	"strings"
)

// ErrInvalidRequest reports native-login input that cannot start an approval.
// Its message contains no callback, challenge or credential supplied by a client.
var ErrInvalidRequest = errors.New("native login: invalid request")

// PortRange is the inclusive loopback interval advertised in login.v1 discovery.
// Keep two distinct endpoints: Terraform 1.17.1 samples [Min, Max), so a single
// port interval does not result in any listen attempt in that client.
type PortRange struct {
	Min int
	Max int
}

// ValidateRedirect accepts the exact localhost callback generated by the pinned
// Terraform client. General native-client IP callbacks are a separate contract;
// DNS resolution must never turn an arbitrary callback host into trusted input.
// The caller retains raw for the authorization code's exact redirect binding.
func ValidateRedirect(raw string, ports PortRange) error {
	if ports.Min < 1024 || ports.Max > 65535 || ports.Min >= ports.Max {
		return ErrInvalidRequest
	}
	u, err := url.Parse(raw)
	if err != nil {
		return ErrInvalidRequest
	}
	port, err := strconv.Atoi(u.Port())
	if err != nil || port < ports.Min || port > ports.Max ||
		raw != "http://localhost:"+strconv.Itoa(port)+"/login" {
		return ErrInvalidRequest
	}
	return nil
}

// ValidatePKCEChallenge requires the public-client S256 method and its canonical
// unpadded base64url SHA-256 challenge (RFC 7636 sections 4.2 and 4.3).
func ValidatePKCEChallenge(challenge, method string) error {
	if method != "S256" || !validChallenge(challenge) {
		return ErrInvalidRequest
	}
	return nil
}

func validChallenge(challenge string) bool {
	if len(challenge) != 43 {
		return false
	}
	b, err := base64.RawURLEncoding.Strict().DecodeString(challenge)
	return err == nil && len(b) == sha256.Size
}

// VerifyPKCE binds redemption to the original S256 challenge. A malformed
// verifier and a mismatch have the same result, so the exchange can answer the
// same invalid_grant without disclosing challenge or verifier values.
func VerifyPKCE(challenge, verifier string) bool {
	if !validChallenge(challenge) || len(verifier) < 43 || len(verifier) > 128 {
		return false
	}
	if strings.IndexFunc(verifier, func(r rune) bool {
		return (r < 'a' || r > 'z') && (r < 'A' || r > 'Z') &&
			(r < '0' || r > '9') && !strings.ContainsRune("-._~", r)
	}) >= 0 {
		return false
	}
	actual := sha256.Sum256([]byte(verifier))
	expected := base64.RawURLEncoding.EncodeToString(actual[:])
	return subtle.ConstantTimeCompare([]byte(challenge), []byte(expected)) == 1
}
