package openapibundle

import (
	"bytes"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"gopkg.in/yaml.v3"
)

// InfoFile holds the document head: openapi, info, servers, tags, security.
const InfoFile = "info.yaml"

// SharedFile is the components fragment that sits beside the service
// directories, not in one, and that every service's bundle merges
// (decision 0043, "Where the declarations live").
const SharedFile = "components-shared.yaml"

// The shared responses the bundle adds to every admitted operation, and the
// x-cost value that marks an operation admission never sees.
const (
	TooManyRequests    = "TooManyRequests"
	ServiceUnavailable = "ServiceUnavailable"
	costExempt         = "exempt"
)

// operationMethods are the keys of a path item that hold an operation.
var operationMethods = map[string]bool{
	"get": true, "put": true, "post": true, "delete": true,
	"options": true, "head": true, "patch": true, "trace": true,
}

var (
	errNoInfo        = errors.New("openapibundle: info.yaml is required")
	errNotMapping    = errors.New("openapibundle: top level is not a mapping")
	errDuplicatePath = errors.New("openapibundle: duplicate path")
	errDuplicateComp = errors.New("openapibundle: duplicate component")
	errDuplicateOpID = errors.New("openapibundle: duplicate operationId")
	errInfoKeys      = errors.New(
		"openapibundle: info.yaml may only hold openapi, info, servers, tags, security, externalDocs",
	)
	errFragmentKeys = errors.New("openapibundle: fragments may only hold paths and components")
	errSharedKeys   = errors.New("openapibundle: " + SharedFile + " may only hold components")
)

// Bundle reads srcDir and returns the merged document as YAML. Keys inside
// paths and each components section are sorted so the output is stable
// regardless of which fragment a path came from. When the directory above
// srcDir holds SharedFile, its components are merged too, and every
// operation whose x-cost is not exempt gains the shared 429 and 503 it does
// not declare itself.
func Bundle(srcDir string) ([]byte, error) {
	info, err := readNode(filepath.Join(srcDir, InfoFile))
	if err != nil {
		return nil, errNoInfo
	}
	for _, k := range mappingKeys(info) {
		switch k {
		case "openapi", "info", "servers", "tags", "security", "externalDocs":
		default:
			return nil, fmt.Errorf("%w: found %q", errInfoKeys, k)
		}
	}
	entries, err := os.ReadDir(srcDir)
	if err != nil {
		return nil, fmt.Errorf("openapibundle: read %s: %w", srcDir, err)
	}
	paths := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	comps := map[string]*yaml.Node{}
	opIDs := map[string]string{}
	names := make([]string, 0, len(entries))
	for _, e := range entries {
		n := e.Name()
		if e.IsDir() || n == InfoFile || !strings.HasSuffix(n, ".yaml") {
			continue
		}
		if !strings.HasPrefix(n, "paths-") && !strings.HasPrefix(n, "components-") {
			continue
		}
		names = append(names, n)
	}
	sort.Strings(names)
	for _, n := range names {
		frag, err := readNode(filepath.Join(srcDir, n))
		if err != nil {
			return nil, err
		}
		for i := 0; i < len(frag.Content); i += 2 {
			key := frag.Content[i].Value
			val := frag.Content[i+1]
			switch key {
			case "paths":
				if err := mergePaths(paths, val, n, opIDs); err != nil {
					return nil, err
				}
			case "components":
				if err := mergeComponents(comps, val, n); err != nil {
					return nil, err
				}
			default:
				return nil, fmt.Errorf("%w: %s has %q", errFragmentKeys, n, key)
			}
		}
	}
	if err := mergeShared(comps, filepath.Join(filepath.Dir(filepath.Clean(srcDir)), SharedFile)); err != nil {
		return nil, err
	}
	injectAdmission(paths, comps["responses"])
	sortMapping(paths)
	doc := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
	for _, k := range []string{"openapi", "info", "servers", "tags", "security", "externalDocs"} {
		if v := lookup(info, k); v != nil {
			doc.Content = append(doc.Content, scalar(k), v)
		}
	}
	doc.Content = append(doc.Content, scalar("paths"), paths)
	if len(comps) > 0 {
		cn := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		kinds := make([]string, 0, len(comps))
		for k := range comps {
			kinds = append(kinds, k)
		}
		sort.Strings(kinds)
		for _, k := range kinds {
			sortMapping(comps[k])
			cn.Content = append(cn.Content, scalar(k), comps[k])
		}
		doc.Content = append(doc.Content, scalar("components"), cn)
	}
	var buf bytes.Buffer
	buf.WriteString(
		"# Generated by `make bundle` from " + filepath.ToSlash(
			srcDir,
		) + "/; edit the fragments, not this file.\n",
	)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(
		&yaml.Node{Kind: yaml.DocumentNode, Content: []*yaml.Node{doc}},
	); err != nil {
		return nil, fmt.Errorf("openapibundle: encode: %w", err)
	}
	if err := enc.Close(); err != nil {
		return nil, fmt.Errorf("openapibundle: close: %w", err)
	}
	return buf.Bytes(), nil
}

// BundleAll bundles every service directory under srcRoot into
// <outDir>/<service>.openapi.yaml and returns the services written.
func BundleAll(srcRoot, outDir string) ([]string, error) {
	entries, err := os.ReadDir(srcRoot)
	if err != nil {
		return nil, fmt.Errorf("openapibundle: read %s: %w", srcRoot, err)
	}
	var done []string
	for _, e := range entries {
		if !e.IsDir() {
			continue
		}
		out, err := Bundle(filepath.Join(srcRoot, e.Name()))
		if err != nil {
			return done, fmt.Errorf("%s: %w", e.Name(), err)
		}
		target := filepath.Join(outDir, e.Name()+".openapi.yaml")
		if err := os.WriteFile(target, out, 0o600); err != nil {
			return done, fmt.Errorf("openapibundle: write %s: %w", target, err)
		}
		done = append(done, e.Name())
	}
	sort.Strings(done)
	return done, nil
}

func readNode(path string) (*yaml.Node, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("openapibundle: read %s: %w", path, err)
	}
	var doc yaml.Node
	if err := yaml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("openapibundle: parse %s: %w", path, err)
	}
	if len(doc.Content) == 0 {
		return &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}, nil
	}
	root := doc.Content[0]
	if root.Kind != yaml.MappingNode {
		return nil, fmt.Errorf("%w: %s", errNotMapping, path)
	}
	return root, nil
}

func mergePaths(dst, src *yaml.Node, frag string, opIDs map[string]string) error {
	if src.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(src.Content); i += 2 {
		p := src.Content[i].Value
		if lookup(dst, p) != nil {
			return fmt.Errorf("%w %s in %s", errDuplicatePath, p, frag)
		}
		item := src.Content[i+1]
		for j := 0; j+1 < len(item.Content); j += 2 {
			if id := lookup(item.Content[j+1], "operationId"); id != nil {
				if prev, ok := opIDs[id.Value]; ok {
					return fmt.Errorf(
						"%w %s in %s (first seen in %s)",
						errDuplicateOpID,
						id.Value,
						frag,
						prev,
					)
				}
				opIDs[id.Value] = frag
			}
		}
		dst.Content = append(dst.Content, src.Content[i], item)
	}
	return nil
}

func mergeComponents(dst map[string]*yaml.Node, src *yaml.Node, frag string) error {
	if src.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i < len(src.Content); i += 2 {
		kind := src.Content[i].Value
		items := src.Content[i+1]
		if dst[kind] == nil {
			dst[kind] = &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map"}
		}
		for j := 0; j+1 < len(items.Content); j += 2 {
			name := items.Content[j].Value
			if lookup(dst[kind], name) != nil {
				return fmt.Errorf("%w %s/%s in %s", errDuplicateComp, kind, name, frag)
			}
			dst[kind].Content = append(dst[kind].Content, items.Content[j], items.Content[j+1])
		}
	}
	return nil
}

// mergeShared merges the shared fragment at path, when there is one, as one
// more components fragment: a service that declares one of its components
// again fails the bundle, as two of its own fragments would.
func mergeShared(comps map[string]*yaml.Node, path string) error {
	if _, err := os.Stat(path); errors.Is(err, os.ErrNotExist) {
		return nil
	}
	frag, err := readNode(path)
	if err != nil {
		return err
	}
	for i := 0; i+1 < len(frag.Content); i += 2 {
		if key := frag.Content[i].Value; key != "components" {
			return fmt.Errorf("%w: found %q", errSharedKeys, key)
		}
		if err := mergeComponents(comps, frag.Content[i+1], SharedFile); err != nil {
			return err
		}
	}
	return nil
}

// injectAdmission gives every operation whose x-cost is not exempt the
// shared 429 and 503 it does not declare itself. An operation without x-cost
// is admitted today, so it counts as not exempt. An operation's own 429 or
// 503 stays: it is declared because admission answers its path in another
// envelope, or because the status also reports a condition of its own.
// Nothing is added when the shared fragment lacks the response, so a bundle
// never references a component it does not hold.
func injectAdmission(paths, responses *yaml.Node) {
	type shared struct{ status, ref string }
	var add []shared
	for _, s := range []shared{{"429", TooManyRequests}, {"503", ServiceUnavailable}} {
		if lookup(responses, s.ref) != nil {
			add = append(add, shared{s.status, "#/components/responses/" + s.ref})
		}
	}
	for i := 1; i < len(paths.Content); i += 2 {
		item := paths.Content[i]
		for j := 0; j+1 < len(item.Content); j += 2 {
			if !operationMethods[item.Content[j].Value] {
				continue
			}
			op := item.Content[j+1]
			if cost := lookup(op, "x-cost"); cost != nil && cost.Value == costExempt {
				continue
			}
			resp := lookup(op, "responses")
			if resp == nil || resp.Kind != yaml.MappingNode {
				continue
			}
			for _, s := range add {
				if lookup(resp, s.status) == nil {
					insertStatus(resp, s.status, s.ref)
				}
			}
		}
	}
}

// insertStatus adds status, referencing ref, before the first response that
// sorts after it, so the bundle lists an operation's statuses in order
// wherever its fragment did. Range keys such as 4XX sort after their codes
// and default after every status.
func insertStatus(resp *yaml.Node, status, ref string) {
	key := &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: status, Style: yaml.SingleQuotedStyle}
	val := &yaml.Node{Kind: yaml.MappingNode, Tag: "!!map", Content: []*yaml.Node{
		scalar("$ref"),
		{Kind: yaml.ScalarNode, Tag: "!!str", Value: ref, Style: yaml.SingleQuotedStyle},
	}}
	at := len(resp.Content)
	for i := 0; i+1 < len(resp.Content); i += 2 {
		k := resp.Content[i].Value
		if k == "default" || len(k) == len(status) && k > status {
			at = i
			break
		}
	}
	resp.Content = append(resp.Content[:at], append([]*yaml.Node{key, val}, resp.Content[at:]...)...)
}

func lookup(m *yaml.Node, key string) *yaml.Node {
	if m == nil || m.Kind != yaml.MappingNode {
		return nil
	}
	for i := 0; i+1 < len(m.Content); i += 2 {
		if m.Content[i].Value == key {
			return m.Content[i+1]
		}
	}
	return nil
}

func mappingKeys(m *yaml.Node) []string {
	var out []string
	for i := 0; i+1 < len(m.Content); i += 2 {
		out = append(out, m.Content[i].Value)
	}
	return out
}

func scalar(v string) *yaml.Node {
	return &yaml.Node{Kind: yaml.ScalarNode, Tag: "!!str", Value: v}
}

// sortMapping orders a mapping node's pairs by key, keeping each value node
// (and its comments and scalar styles) intact.
func sortMapping(m *yaml.Node) {
	type pair struct{ k, v *yaml.Node }
	pairs := make([]pair, 0, len(m.Content)/2)
	for i := 0; i+1 < len(m.Content); i += 2 {
		pairs = append(pairs, pair{m.Content[i], m.Content[i+1]})
	}
	sort.SliceStable(pairs, func(i, j int) bool { return pairs[i].k.Value < pairs[j].k.Value })
	m.Content = m.Content[:0]
	for _, p := range pairs {
		m.Content = append(m.Content, p.k, p.v)
	}
}
