const fixtureSpec = `openapi: 3.0.3
servers:
  - url: /artifactory
paths:
  /api/build/append/{buildName}/{buildNumber}:
    post:
      operationId: appendBuild
      x-idempotency: key
      x-cost: expensive
      parameters:
        - $ref: '#/components/parameters/IdempotencyKey'
  /api/storage/{repoKey}/{itemPath}:
    parameters:
      - name: repoKey
        in: path
    get:
      operationId: getStorageItem
      x-idempotency: safe
      x-cost: ordinary
      x-cost-expensive-query: [list]
      x-pagination: complete
    delete:
      operationId: deleteItemProperties
  /api/docker/{repo-key}/v2/{imageName*}/tags/list:
    get:
      operationId: listDockerTags
      x-handwritten: true
  /api/keyed/{id}:
    parameters:
      - $ref: '#/components/parameters/IdempotencyKey'
    put:
      operationId: keyedByPathItem
`

func writeSpec(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

func TestUnitLoadAndRender(t *testing.T) {
	dir := t.TempDir()
	writeSpec(t, dir, "artifactory.openapi.yaml", fixtureSpec)
	writeSpec(
		t,
		dir,
		"access.openapi.yaml",
		"servers:\n  - url: /access\npaths:\n  /api/v1/system/ping:\n    get:\n      operationId: accessPing\n      x-cost: exempt\n",
	)
	writeSpec(t, dir, "ignored.yaml", "not: a spec\n")
	rows, err := Load(dir)
	if err != nil {
		t.Fatal(err)
	}
	want := []Row{
		{
			Service:     "access",
			Method:      "GET",
			Pattern:     "/access/api/v1/system/ping",
			OperationID: "accessPing",
			Cost:        "exempt",
		},
		{
			Service:        "artifactory",
			Method:         "POST",
			Pattern:        "/artifactory/api/build/append/{buildName}/{buildNumber}",
			OperationID:    "appendBuild",
			Cost:           "expensive",
			Idempotency:    "key",
			IdempotencyKey: true,
		},
		{
			Service:     "artifactory",
			Method:      "GET",
			Pattern:     "/artifactory/api/docker/{repo-key}/v2/{imageName}/tags/list",
			OperationID: "listDockerTags",
			Handwritten: true,
		},
		{
			Service: "artifactory", Method: "PUT", Pattern: "/artifactory/api/keyed/{id}",
			OperationID: "keyedByPathItem", IdempotencyKey: true,
		},
		{
			Service:     "artifactory",
			Method:      "DELETE",
			Pattern:     "/artifactory/api/storage/{repoKey}/{itemPath}",
			OperationID: "deleteItemProperties",
		},
		{
			Service:        "artifactory",
			Method:         "GET",
			Pattern:        "/artifactory/api/storage/{repoKey}/{itemPath}",
			OperationID:    "getStorageItem",
			Cost:           "ordinary",
			ExpensiveQuery: []string{"list"},
			Idempotency:    "safe",
			Pagination:     "complete",
		},
	}
	if diff := cmp.Diff(want, rows); diff != "" {
		t.Fatal(diff)
	}
	src, err := Render("operations", rows)
	if err != nil {
		t.Fatal(err)
	}
	text := string(src)
	for _, s := range []string{
		"// Code generated by tools/optable from api/*.openapi.yaml. DO NOT EDIT.",
		"package operations",
		`{Service: "artifactory", Method: "GET", Pattern: "/artifactory/api/storage/{repoKey}/{itemPath}", ` +
			`OperationID: "getStorageItem", Cost: "ordinary", Idempotency: "safe", Pagination: "complete", ` +
			`ExpensiveQuery: []string{"list"}},`,
		`OperationID: "listDockerTags", Handwritten: true},`,
		`Idempotency: "key", IdempotencyKey: true},`,
		`OperationID: "deleteItemProperties"},`,
	} {
		if !strings.Contains(text, s) {
			t.Errorf("rendered table lacks %q:\n%s", s, text)
		}
	}
}

func TestUnitChiPattern(t *testing.T) {
	for in, want := range map[string]string{
		"/a/{b}":         "/base/a/{b}",
		"/a/{.b}/{;c*}":  "/base/a/{b}/{c}",
		"/a/{?b}/static": "/base/a/{b}/static",
	} {
		if got := ChiPattern("/base", in); got != want {
			t.Errorf("ChiPattern(%q) = %q, want %q", in, got, want)
		}
	}
}

func TestUnitRun(t *testing.T) {
	dir := t.TempDir()
	writeSpec(t, dir, "artifactory.openapi.yaml", fixtureSpec)
	out := filepath.Join(t.TempDir(), "optbl", "table.gen.go")
	if err := os.MkdirAll(filepath.Dir(out), 0o750); err != nil {
		t.Fatal(err)
	}
	n, err := Run(dir, out)
	if err != nil {
		t.Fatal(err)
	}
	if n != 5 {
		t.Fatalf("wrote %d operations, want 5", n)
	}
	src, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(src), "package optbl\n") {
		t.Fatalf("package not taken from the directory:\n%s", src)
	}
}

func TestUnitErrors(t *testing.T) {
	cases := map[string]map[string]string{
		"no specs":    {},
		"unparsable":  {"a.openapi.yaml": "paths: [\n"},
		"not mapping": {"a.openapi.yaml": "- a\n"},
		"empty":       {"a.openapi.yaml": ""},
		"no server":   {"a.openapi.yaml": "paths: {}\n"},
		"server url":  {"a.openapi.yaml": "servers:\n  - description: x\n"},
		"duplicate": {
			"a.openapi.yaml": "servers:\n  - url: /x\npaths:\n  /p:\n    get:\n      operationId: a\n",
			"b.openapi.yaml": "servers:\n  - url: /x\npaths:\n  /p:\n    get:\n      operationId: b\n",
		},
		"unreadable": {"a.openapi.yaml/": ""},
	}
	for name, files := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			for n, body := range files {
				if strings.HasSuffix(n, "/") {
					// A directory named like a spec cannot be read as one.
					if err := os.MkdirAll(filepath.Join(dir, n), 0o750); err != nil {
						t.Fatal(err)
					}
					continue
				}
				writeSpec(t, dir, n, body)
			}
			if _, err := Load(dir); err == nil {
				t.Fatal("expected an error")
			}
			if _, err := Run(dir, filepath.Join(dir, "out.gen.go")); err == nil {
				t.Fatal("expected Run to fail too")
			}
		})
	}
	if _, err := Load("["); err == nil {
		t.Fatal("expected a bad glob pattern to fail")
	}
	dir := t.TempDir()
	writeSpec(t, dir, "a.openapi.yaml", fixtureSpec)
	if _, err := Run(dir, filepath.Join(dir, "missing", "out.gen.go")); err == nil {
		t.Fatal("expected a write into a missing directory to fail")
	}
	if _, err := Render("not a package name", nil); err == nil {
		t.Fatal("expected source that does not format to fail")
	}
}
