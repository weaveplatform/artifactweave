-- Snapshot full sync (PEER-05, decision 0021). A sender keeps the
-- snapshots it has taken for its receivers in stream_snapshots and
-- stream_snapshot_entries, so the pages of one stay as they were at its
-- sequence while the stream moves on; entries are read in byte order of
-- key, hence COLLATE "C", ordering as SQLite does. A receiver records how
-- far a run has got in full_sync_runs, with each applied page, and the
-- run resynchronising a flagged stream in stream_resyncs.run.
-- +up
ALTER TABLE full_sync_runs ADD COLUMN stream TEXT NOT NULL DEFAULT '';
ALTER TABLE full_sync_runs ADD COLUMN phase TEXT NOT NULL DEFAULT '';
ALTER TABLE full_sync_runs ADD COLUMN page_cursor TEXT NOT NULL DEFAULT '';
ALTER TABLE full_sync_runs ADD COLUMN last_key TEXT NOT NULL DEFAULT '';
ALTER TABLE full_sync_runs ADD COLUMN message TEXT NOT NULL DEFAULT '';
ALTER TABLE stream_resyncs ADD COLUMN run BIGINT NOT NULL DEFAULT 0;
CREATE TABLE stream_snapshots (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stream   TEXT NOT NULL,
    receiver TEXT NOT NULL,
    sequence BIGINT NOT NULL DEFAULT 0,
    taken_at BIGINT,
    read_at  BIGINT
);
CREATE INDEX stream_snapshots_receiver ON stream_snapshots (receiver, stream);
CREATE TABLE stream_snapshot_entries (
    snapshot_id BIGINT NOT NULL,
    item_key    TEXT COLLATE "C" NOT NULL,
    hlc_wall    BIGINT NOT NULL,
    hlc_logical BIGINT NOT NULL,
    origin      TEXT NOT NULL,
    deleted     BOOLEAN NOT NULL DEFAULT FALSE,
    payload     BYTEA,
    blob_sha256 TEXT NOT NULL DEFAULT '',
    blob_size   BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (snapshot_id, item_key)
);
-- +down
DROP TABLE stream_snapshot_entries;
DROP INDEX stream_snapshots_receiver;
DROP TABLE stream_snapshots;
ALTER TABLE stream_resyncs DROP COLUMN run;
ALTER TABLE full_sync_runs DROP COLUMN message;
ALTER TABLE full_sync_runs DROP COLUMN last_key;
ALTER TABLE full_sync_runs DROP COLUMN page_cursor;
ALTER TABLE full_sync_runs DROP COLUMN phase;
ALTER TABLE full_sync_runs DROP COLUMN stream;
