// Package stubgen writes a type that implements a generated strict server
// interface by answering 501 for every operation. oapi-codegen emits an
// Unimplemented type for the plain ServerInterface but not for the strict one,
// and the strict one is what internal/server implements; without a stub every
// scaffolded operation would have to be hand-stubbed before the tree compiles.
package stubgen

import (
	"bytes"
	"errors"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/token"
	"os"
	"strings"
)

// InterfaceName is the strict interface oapi-codegen generates.
const InterfaceName = "StrictServerInterface"

// TypeName is the stub type written into the generated package.
const TypeName = "UnimplementedStrict"

var (
	errNoInterface = errors.New("stubgen: interface not found")
	errNoPackage   = errors.New("stubgen: no package clause")
)

// Method is one interface method: name, request type and response type.
type Method struct {
	Name     string
	Request  string
	Response string
}

// Parse extracts the strict interface methods from generated source.
func Parse(src []byte) (string, []Method, error) {
	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, "server.gen.go", src, 0)
	if err != nil {
		return "", nil, fmt.Errorf("stubgen: parse: %w", err)
	}
	if f.Name == nil {
		return "", nil, errNoPackage
	}
	var methods []Method
	found := false
	for _, decl := range f.Decls {
		gd, ok := decl.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, spec := range gd.Specs {
			ts, ok := spec.(*ast.TypeSpec)
			if !ok || ts.Name.Name != InterfaceName {
				continue
			}
			it, ok := ts.Type.(*ast.InterfaceType)
			if !ok {
				continue
			}
			found = true
			for _, m := range it.Methods.List {
				ft, ok := m.Type.(*ast.FuncType)
				if !ok || len(m.Names) == 0 {
					continue
				}
				methods = append(methods, Method{
					Name:     m.Names[0].Name,
					Request:  typeString(ft.Params.List[len(ft.Params.List)-1].Type),
					Response: typeString(ft.Results.List[0].Type),
				})
			}
		}
	}
	if !found {
		return "", nil, fmt.Errorf("%w: %s", errNoInterface, InterfaceName)
	}
	return f.Name.Name, methods, nil
}

func typeString(e ast.Expr) string {
	switch t := e.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.SelectorExpr:
		return typeString(t.X) + "." + t.Sel.Name
	case *ast.StarExpr:
		return "*" + typeString(t.X)
	default:
		return "any"
	}
}

// Generate renders the stub file for the parsed package. Every method returns
// apierror.ErrNotImplemented, which internal/server's response error handler
// renders as 501 in the surface's envelope.
func Generate(pkg string, methods []Method) ([]byte, error) {
	var b bytes.Buffer
	b.WriteString("// Code generated by tools/stubgen. DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package %s\n\n", pkg)
	// An interface with no operations (a spec whose paths are still empty)
	// must not import packages it does not use.
	if len(methods) > 0 {
		b.WriteString("import (\n\t\"context\"\n\n")
		b.WriteString(
			"\t\"github.com/weaveplatform/weaveplatform-artifact-registry/internal/server/apierror\"\n)\n\n",
		)
	}
	fmt.Fprintf(
		&b,
		"// %s answers 501 for every strict operation. Services embed it and\n",
		TypeName,
	)
	b.WriteString("// override the operations they implement.\n")
	fmt.Fprintf(&b, "type %s struct{}\n\n", TypeName)
	fmt.Fprintf(&b, "var _ %s = %s{}\n\n", InterfaceName, TypeName)
	for _, m := range methods {
		fmt.Fprintf(
			&b,
			"func (%s) %s(context.Context, %s) (%s, error) {\n\treturn nil, apierror.ErrNotImplemented\n}\n\n",
			TypeName,
			m.Name,
			m.Request,
			m.Response,
		)
	}
	out, err := format.Source(b.Bytes())
	if err != nil {
		return nil, fmt.Errorf("stubgen: format: %w", err)
	}
	return out, nil
}

// Run reads a generated server file and writes the stub next to it.
func Run(genPath, outPath string) (int, error) {
	src, err := os.ReadFile(genPath)
	if err != nil {
		return 0, fmt.Errorf("stubgen: read %s: %w", genPath, err)
	}
	pkg, methods, err := Parse(src)
	if err != nil {
		return 0, err
	}
	out, err := Generate(pkg, methods)
	if err != nil {
		return 0, err
	}
	if outPath == "" {
		outPath = strings.TrimSuffix(genPath, "server.gen.go") + "unimplemented.gen.go"
	}
	if err := os.WriteFile(outPath, out, 0o600); err != nil {
		return 0, fmt.Errorf("stubgen: write %s: %w", outPath, err)
	}
	return len(methods), nil
}
