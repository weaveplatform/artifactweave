package stubgen

import (
	"go/ast"
	"go/importer"
	"go/parser"
	"go/token"
	"go/types"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// fixture mimics the slice of oapi-codegen output stubgen reads: the strict
// interface plus the request and response types it names, with a throwaway
// operation that no service implements.
const fixture = `package throwaway

import "context"

type ThrowawayRequestObject struct{}

type ThrowawayResponseObject interface{ VisitThrowawayResponse() error }

type Other struct{}

// StrictServerInterface represents all server handlers.
type StrictServerInterface interface {
	// Throwaway operation
	Throwaway(ctx context.Context, request ThrowawayRequestObject) (ThrowawayResponseObject, error)
}
`

func TestParseAndGenerate(t *testing.T) {
	pkg, methods, err := Parse([]byte(fixture))
	if err != nil {
		t.Fatal(err)
	}
	if pkg != "throwaway" || len(methods) != 1 {
		t.Fatalf("pkg %q methods %+v", pkg, methods)
	}
	if methods[0] != (Method{Name: "Throwaway", Request: "ThrowawayRequestObject", Response: "ThrowawayResponseObject"}) {
		t.Fatalf("method %+v", methods[0])
	}
	out, err := Generate(pkg, methods)
	if err != nil {
		t.Fatal(err)
	}
	src := string(out)
	for _, want := range []string{
		"// Code generated by tools/stubgen. DO NOT EDIT.",
		"type UnimplementedStrict struct{}",
		"var _ StrictServerInterface = UnimplementedStrict{}",
		"func (UnimplementedStrict) Throwaway(context.Context, ThrowawayRequestObject) (ThrowawayResponseObject, error)",
		"return nil, apierror.ErrNotImplemented",
	} {
		if !strings.Contains(src, want) {
			t.Errorf("generated stub lacks %q:\n%s", want, src)
		}
	}
	// The stub must type-check against the fixture package: that is the
	// "compiles" half of the proof; the 501 half lives in internal/server.
	fset := token.NewFileSet()
	files := []*fileSrc{{"server.gen.go", fixture}, {"unimplemented.gen.go", src}}
	var asts []*ast.File
	for _, f := range files {
		af, err := parser.ParseFile(fset, f.name, f.src, 0)
		if err != nil {
			t.Fatalf("parse %s: %v", f.name, err)
		}
		asts = append(asts, af)
	}
	conf := types.Config{Importer: importer.ForCompiler(fset, "source", nil)}
	if _, err := conf.Check("throwaway", fset, asts, nil); err != nil {
		t.Fatalf("stub does not type-check: %v\n%s", err, src)
	}
}

type fileSrc struct{ name, src string }

func TestGenerateNoMethods(t *testing.T) {
	out, err := Generate("empty", nil)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Contains(string(out), "import") {
		t.Fatalf("empty stub must not import anything:\n%s", out)
	}
}

func TestParseErrors(t *testing.T) {
	if _, _, err := Parse([]byte("package x\n")); err == nil {
		t.Fatal("expected missing interface error")
	}
	if _, _, err := Parse([]byte("not go")); err == nil {
		t.Fatal("expected parse error")
	}
}

func TestRun(t *testing.T) {
	dir := t.TempDir()
	gen := filepath.Join(dir, "server.gen.go")
	if err := os.WriteFile(gen, []byte(fixture), 0o600); err != nil {
		t.Fatal(err)
	}
	n, err := Run(gen, "")
	if err != nil {
		t.Fatal(err)
	}
	if n != 1 {
		t.Fatalf("stubbed %d, want 1", n)
	}
	if _, err := os.Stat(filepath.Join(dir, "unimplemented.gen.go")); err != nil {
		t.Fatalf("default output path not written: %v", err)
	}
	if _, err := Run(filepath.Join(dir, "missing.go"), ""); err == nil {
		t.Fatal("expected read error")
	}
	bad := filepath.Join(dir, "bad.go")
	if err := os.WriteFile(bad, []byte("package x\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if _, err := Run(bad, ""); err == nil {
		t.Fatal("expected interface error")
	}
	if _, err := Run(gen, filepath.Join(dir, "nope", "out.go")); err == nil {
		t.Fatal("expected write error")
	}
}

func TestTypeString(t *testing.T) {
	cases := map[string]string{
		"x":       "x",
		"pkg.T":   "pkg.T",
		"*pkg.T":  "*pkg.T",
		"[]byte":  "any",
		"map[a]b": "any",
		"func()":  "any",
	}
	for src, want := range cases {
		expr, err := parser.ParseExpr(src)
		if err != nil {
			t.Fatal(err)
		}
		if got := typeString(expr); got != want {
			t.Errorf("%s: got %q want %q", src, got, want)
		}
	}
}
