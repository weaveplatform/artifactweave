-- The artifacts stream: blobs and the mirror members that hold them, on the
-- hot and the archive tier; repositories with their sealed secrets, virtual
-- members, key pair roles and sealed header values; items with their
-- properties and statistics; the trash; the package index; archived items;
-- build-info; remote retrieval state; Git LFS locks and Bower registrations.
-- Research 15 section 4.
--
-- Text columns that lists sort or page by are COLLATE "C", so PostgreSQL
-- orders them byte by byte, as SQLite and the in-memory store do.
-- +up

-- state is where a blob stands in garbage collection (decision 0010): a row
-- is marked deleting before its content is removed and becomes deleted (a
-- tombstone) afterwards, so a deploy of the same content never references
-- content being removed. deleted_at is kept on a revived row until pruned:
-- a deploy that finds it set checks the content is still there.
CREATE TABLE blobs (
    sha256     TEXT COLLATE "C" PRIMARY KEY,
    sha512     TEXT NOT NULL DEFAULT '',
    sha1       TEXT NOT NULL DEFAULT '',
    md5        TEXT NOT NULL DEFAULT '',
    size       BIGINT NOT NULL,
    created_at BIGINT,
    ref_count  BIGINT NOT NULL DEFAULT 0,
    state      TEXT NOT NULL DEFAULT 'live',
    deleted_at BIGINT
);
-- Checksum deploy and the checksum searches look content up by sha1 and
-- md5 (sha256 is the key). Nothing looks it up by sha512: whatever holds a
-- sha512 holds the sha256 too, so it has no index.
CREATE INDEX blobs_sha1 ON blobs (sha1);
CREATE INDEX blobs_md5 ON blobs (md5);
CREATE INDEX blobs_unreferenced ON blobs (ref_count, sha256);
CREATE INDEX blobs_state ON blobs (state, sha256);

-- The document is the repository configuration without its password and
-- its sensitive header values, which live sealed in repository_secrets and
-- repository_header_secrets, so no document read can leak them.
-- header_secrets_version 0 marks a document that may still hold header
-- values; the artifacts module moves them into sealed rows with the
-- configured keyring when the store opens, because DDL never sees key
-- material (decision 0017).
CREATE TABLE repositories (
    key                    TEXT COLLATE "C" PRIMARY KEY,
    rclass                 TEXT NOT NULL,
    package_type           TEXT NOT NULL DEFAULT '',
    project_key            TEXT NOT NULL DEFAULT '',
    created_at             BIGINT NOT NULL,
    updated_at             BIGINT NOT NULL,
    doc                    TEXT NOT NULL,
    header_secrets_version INTEGER NOT NULL DEFAULT 0
);
CREATE INDEX repositories_class ON repositories (rclass, key);
CREATE INDEX repositories_package_type ON repositories (package_type, key);
CREATE INDEX repositories_project ON repositories (project_key, key);

CREATE TABLE repository_secrets (
    repo_key TEXT COLLATE "C" PRIMARY KEY REFERENCES repositories (key) ON DELETE CASCADE,
    password BYTEA NOT NULL
);

CREATE TABLE repository_members (
    virtual_key TEXT COLLATE "C" NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    member_key  TEXT COLLATE "C" NOT NULL,
    position    INTEGER NOT NULL,
    PRIMARY KEY (virtual_key, position)
);
CREATE INDEX repository_members_member ON repository_members (member_key, virtual_key);

CREATE TABLE repository_keypairs (
    repo_key     TEXT COLLATE "C" NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    role         TEXT NOT NULL,
    keypair_name TEXT NOT NULL,
    PRIMARY KEY (repo_key, role)
);
CREATE INDEX repository_keypairs_name ON repository_keypairs (keypair_name, repo_key);

CREATE TABLE repository_header_secrets (
    repo_key TEXT COLLATE "C" NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    position INTEGER NOT NULL,
    name     TEXT COLLATE "C" NOT NULL,
    value    BYTEA,
    PRIMARY KEY (repo_key, position)
);

-- Every AQL items-domain field is a column. No foreign key to repositories:
-- deleting a configuration and deleting its content are separate steps.
-- props_modified_at is when the item's properties last changed, which the
-- storage API lists as mdTimestamps.properties, and NULL while it has none.
-- Artifactory 6.20 keeps that time in a table of its own
-- (node_meta_infos.props_modified); nothing else from that table is kept,
-- so a column is enough.
CREATE TABLE items (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_key          TEXT COLLATE "C" NOT NULL,
    cached            BOOLEAN NOT NULL,
    path              TEXT COLLATE "C" NOT NULL,
    name              TEXT COLLATE "C" NOT NULL,
    depth             INTEGER NOT NULL,
    type              TEXT NOT NULL,
    size              BIGINT NOT NULL DEFAULT 0,
    sha256            TEXT NOT NULL DEFAULT '',
    sha512            TEXT NOT NULL DEFAULT '',
    sha1              TEXT NOT NULL DEFAULT '',
    md5               TEXT NOT NULL DEFAULT '',
    original_sha256   TEXT NOT NULL DEFAULT '',
    original_sha512   TEXT NOT NULL DEFAULT '',
    original_sha1     TEXT NOT NULL DEFAULT '',
    original_md5      TEXT NOT NULL DEFAULT '',
    mime_type         TEXT NOT NULL DEFAULT '',
    created_at        BIGINT,
    created_by        TEXT NOT NULL DEFAULT '',
    modified_at       BIGINT,
    modified_by       TEXT NOT NULL DEFAULT '',
    updated_at        BIGINT,
    remote_url        TEXT NOT NULL DEFAULT '',
    props_modified_at BIGINT
);
CREATE UNIQUE INDEX items_natural ON items (repo_key, cached, path, name);
CREATE INDEX items_sha256 ON items (sha256);
CREATE INDEX items_sha1 ON items (sha1);
CREATE INDEX items_md5 ON items (md5);
CREATE INDEX items_modified ON items (modified_at);
CREATE INDEX items_created ON items (created_at);

-- No key holds a whole value. The stores keep values up to
-- PropertyValueMax, 2400 UTF-16 code units or up to 7 KB of UTF-8, which
-- the B-tree entry limit (2704 bytes) cannot hold (decision 0004).
--
-- Uniqueness is on md5(value): an index expression must be IMMUTABLE, and
-- sha256 needs convert_to, which is only STABLE. Each write replaces every
-- value of a key, so the index only folds duplicates within one write; a
-- crafted collision can drop one of two values the same caller sent,
-- nothing more.
--
-- Lookups by value use the first 255 characters (at most 1020 bytes), as
-- Artifactory's own PostgreSQL index did from its 3.1.1 conversion;
-- migration/artifacts/core/aql narrows on that prefix (valuePrefixLen),
-- then compares the whole value.
CREATE TABLE item_properties (
    item_id BIGINT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    key     TEXT COLLATE "C" NOT NULL,
    value   TEXT COLLATE "C" NOT NULL
);
CREATE UNIQUE INDEX item_properties_unique ON item_properties (item_id, key, md5(value));
CREATE INDEX item_properties_value ON item_properties (key, left(value, 255));

CREATE TABLE item_stats (
    item_id                   BIGINT PRIMARY KEY REFERENCES items (id) ON DELETE CASCADE,
    download_count            BIGINT NOT NULL DEFAULT 0,
    last_downloaded_at        BIGINT,
    last_downloaded_by        TEXT NOT NULL DEFAULT '',
    remote_download_count     BIGINT NOT NULL DEFAULT 0,
    remote_last_downloaded_at BIGINT,
    remote_last_downloaded_by TEXT NOT NULL DEFAULT '',
    remote_origin             TEXT NOT NULL DEFAULT '',
    remote_path               TEXT NOT NULL DEFAULT ''
);

CREATE TABLE trash (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    original_repo_key TEXT COLLATE "C" NOT NULL,
    original_path     TEXT COLLATE "C" NOT NULL,
    original_name     TEXT COLLATE "C" NOT NULL,
    item_json         TEXT NOT NULL,
    deleted_at        BIGINT,
    deleted_by        TEXT NOT NULL DEFAULT ''
);
CREATE INDEX trash_original ON trash (original_repo_key, original_path, original_name, id);
CREATE INDEX trash_deleted ON trash (deleted_at, id);

CREATE TABLE packages (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    repo_key     TEXT COLLATE "C" NOT NULL,
    package_type TEXT NOT NULL DEFAULT '',
    name         TEXT COLLATE "C" NOT NULL,
    created_at   BIGINT
);
CREATE UNIQUE INDEX packages_name ON packages (repo_key, name);

CREATE TABLE package_versions (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    package_id         BIGINT NOT NULL REFERENCES packages (id) ON DELETE CASCADE,
    version            TEXT COLLATE "C" NOT NULL,
    order_key          BIGINT NOT NULL DEFAULT 0,
    created_at         BIGINT,
    last_downloaded_at BIGINT,
    metadata           TEXT
);
CREATE UNIQUE INDEX package_versions_version ON package_versions (package_id, version);
CREATE INDEX package_versions_order ON package_versions (package_id, order_key, version);

CREATE TABLE package_version_files (
    version_id BIGINT NOT NULL REFERENCES package_versions (id) ON DELETE CASCADE,
    item_id    BIGINT NOT NULL REFERENCES items (id) ON DELETE CASCADE,
    PRIMARY KEY (version_id, item_id)
);
CREATE INDEX package_version_files_item ON package_version_files (item_id, version_id);

-- Which mirror members hold which blobs (decision 0028), here for the hot
-- tier and in cold_blob_replicas for the archive tier. updated_at is 0 when
-- unset rather than NULL, because the repair worker pages by (updated_at,
-- sha256, member) and the engines sort NULLs differently.
CREATE TABLE blob_replicas (
    sha256     TEXT COLLATE "C" NOT NULL,
    member     TEXT COLLATE "C" NOT NULL,
    state      TEXT NOT NULL,
    size       BIGINT NOT NULL DEFAULT 0,
    attempts   INTEGER NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '',
    updated_at BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (sha256, member)
);
CREATE INDEX blob_replicas_queue ON blob_replicas (state, member, updated_at, sha256);
CREATE INDEX blob_replicas_member ON blob_replicas (member, updated_at, sha256);

-- The archive tier's content, tracked like blobs, garbage collection states
-- included.
CREATE TABLE cold_blobs (
    sha256     TEXT COLLATE "C" PRIMARY KEY,
    sha512     TEXT NOT NULL DEFAULT '',
    sha1       TEXT NOT NULL DEFAULT '',
    md5        TEXT NOT NULL DEFAULT '',
    size       BIGINT NOT NULL,
    created_at BIGINT,
    ref_count  BIGINT NOT NULL DEFAULT 0,
    state      TEXT NOT NULL DEFAULT 'live',
    deleted_at BIGINT
);
CREATE INDEX cold_blobs_sha1 ON cold_blobs (sha1);
CREATE INDEX cold_blobs_md5 ON cold_blobs (md5);
CREATE INDEX cold_blobs_unreferenced ON cold_blobs (ref_count, sha256);
CREATE INDEX cold_blobs_state ON cold_blobs (state, sha256);

CREATE TABLE cold_blob_replicas (
    sha256     TEXT COLLATE "C" NOT NULL,
    member     TEXT COLLATE "C" NOT NULL,
    state      TEXT NOT NULL,
    size       BIGINT NOT NULL DEFAULT 0,
    attempts   INTEGER NOT NULL DEFAULT 0,
    last_error TEXT NOT NULL DEFAULT '',
    updated_at BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (sha256, member)
);
CREATE INDEX cold_blob_replicas_queue ON cold_blob_replicas (state, member, updated_at, sha256);
CREATE INDEX cold_blob_replicas_member ON cold_blob_replicas (member, updated_at, sha256);

-- Archived items keep the AQL items-domain columns for retention search and
-- the full item, properties and statistics as documents for restore.
CREATE TABLE archived_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    namespace        TEXT NOT NULL DEFAULT '',
    repo_key         TEXT COLLATE "C" NOT NULL,
    path             TEXT COLLATE "C" NOT NULL,
    name             TEXT COLLATE "C" NOT NULL,
    depth            INTEGER NOT NULL DEFAULT 0,
    sha256           TEXT NOT NULL DEFAULT '',
    sha512           TEXT NOT NULL DEFAULT '',
    sha1             TEXT NOT NULL DEFAULT '',
    md5              TEXT NOT NULL DEFAULT '',
    size             BIGINT NOT NULL DEFAULT 0,
    created_at       BIGINT,
    created_by       TEXT NOT NULL DEFAULT '',
    modified_at      BIGINT,
    modified_by      TEXT NOT NULL DEFAULT '',
    package_type     TEXT NOT NULL DEFAULT '',
    package_name     TEXT NOT NULL DEFAULT '',
    package_version  TEXT NOT NULL DEFAULT '',
    policy_key       TEXT NOT NULL DEFAULT '',
    execution_id     BIGINT NOT NULL DEFAULT 0,
    archived_at      BIGINT,
    expires_at       BIGINT,
    cold_blob_sha256 TEXT NOT NULL DEFAULT '',
    item             TEXT NOT NULL,
    properties       TEXT,
    stats            TEXT
);
CREATE INDEX archived_items_location ON archived_items (repo_key, path, name, id);
CREATE INDEX archived_items_policy ON archived_items (policy_key, id);
CREATE INDEX archived_items_execution ON archived_items (execution_id, id);
CREATE INDEX archived_items_expires ON archived_items (expires_at, id);
CREATE INDEX archived_items_sha256 ON archived_items (sha256);
CREATE INDEX archived_items_sha1 ON archived_items (sha1);

-- Build-info (decision 0014, research 22 section 3). One row per run, keyed
-- by (project_key, name, number, started_at), because one build number may
-- be published several times and each publish is a new run (research 22
-- section 3.3). The document is kept as published for the read API;
-- modules, properties, artifacts and dependencies are kept as rows for the
-- AQL build domains, which join to items by checksum.
CREATE TABLE builds (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_key TEXT COLLATE "C" NOT NULL DEFAULT '',
    name        TEXT COLLATE "C" NOT NULL,
    number      TEXT COLLATE "C" NOT NULL,
    started_at  BIGINT NOT NULL,
    url         TEXT NOT NULL DEFAULT '',
    created_at  BIGINT,
    created_by  TEXT NOT NULL DEFAULT '',
    modified_at BIGINT,
    modified_by TEXT NOT NULL DEFAULT '',
    document    TEXT,
    UNIQUE (project_key, name, number, started_at)
);
-- A name's runs newest first, and its latest run.
CREATE INDEX builds_latest ON builds (project_key, name, started_at, id);

-- Modules in document order.
CREATE TABLE build_modules (
    build_id  BIGINT NOT NULL,
    position  INTEGER NOT NULL,
    module_id TEXT NOT NULL DEFAULT '',
    type      TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (build_id, position),
    FOREIGN KEY (build_id) REFERENCES builds (id) ON DELETE CASCADE
);

-- Build-level properties (module_position -1) and module properties, one
-- row per value, for the AQL build.property and module.property domains.
-- Keyed like item_properties, for the same reasons.
CREATE TABLE build_properties (
    build_id        BIGINT NOT NULL,
    module_position INTEGER NOT NULL,
    key             TEXT COLLATE "C" NOT NULL,
    value           TEXT COLLATE "C" NOT NULL,
    FOREIGN KEY (build_id) REFERENCES builds (id) ON DELETE CASCADE
);
CREATE UNIQUE INDEX build_properties_unique ON build_properties (build_id, module_position, key, md5(value));
CREATE INDEX build_properties_value ON build_properties (key, left(value, 255));

-- What each module produced, in document order.
CREATE TABLE build_artifacts (
    build_id        BIGINT NOT NULL,
    module_position INTEGER NOT NULL,
    position        INTEGER NOT NULL,
    name            TEXT NOT NULL DEFAULT '',
    type            TEXT NOT NULL DEFAULT '',
    path            TEXT NOT NULL DEFAULT '',
    sha1            TEXT NOT NULL DEFAULT '',
    sha256          TEXT NOT NULL DEFAULT '',
    md5             TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (build_id, module_position, position),
    FOREIGN KEY (build_id, module_position) REFERENCES build_modules (build_id, position) ON DELETE CASCADE
);
CREATE INDEX build_artifacts_sha1 ON build_artifacts (sha1);
CREATE INDEX build_artifacts_sha256 ON build_artifacts (sha256);

-- What each module consumed, in document order.
CREATE TABLE build_dependencies (
    build_id        BIGINT NOT NULL,
    module_position INTEGER NOT NULL,
    position        INTEGER NOT NULL,
    dependency_id   TEXT NOT NULL DEFAULT '',
    name            TEXT NOT NULL DEFAULT '',
    type            TEXT NOT NULL DEFAULT '',
    path            TEXT NOT NULL DEFAULT '',
    scopes          TEXT,
    sha1            TEXT NOT NULL DEFAULT '',
    sha256          TEXT NOT NULL DEFAULT '',
    md5             TEXT NOT NULL DEFAULT '',
    PRIMARY KEY (build_id, module_position, position),
    FOREIGN KEY (build_id, module_position) REFERENCES build_modules (build_id, position) ON DELETE CASCADE
);
CREATE INDEX build_dependencies_sha1 ON build_dependencies (sha1);
CREATE INDEX build_dependencies_sha256 ON build_dependencies (sha256);

-- Promotions of a run, oldest first.
CREATE TABLE build_promotions (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    build_id    BIGINT NOT NULL,
    created_at  BIGINT,
    created_by  TEXT NOT NULL DEFAULT '',
    status      TEXT NOT NULL DEFAULT '',
    comment     TEXT NOT NULL DEFAULT '',
    ci_user     TEXT NOT NULL DEFAULT '',
    source_repo TEXT NOT NULL DEFAULT '',
    repo        TEXT NOT NULL DEFAULT '',
    FOREIGN KEY (build_id) REFERENCES builds (id) ON DELETE CASCADE
);
CREATE INDEX build_promotions_build ON build_promotions (build_id, created_at, id);

-- The retention a document asked for, kept per build name.
CREATE TABLE build_retention (
    project_key        TEXT COLLATE "C" NOT NULL DEFAULT '',
    name               TEXT COLLATE "C" NOT NULL,
    count              INTEGER NOT NULL DEFAULT 0,
    minimum_build_date BIGINT,
    delete_artifacts   BOOLEAN NOT NULL DEFAULT FALSE,
    keep_numbers       TEXT,
    PRIMARY KEY (project_key, name)
);

-- A durable lifetime per repository (remote_sources) and the raw upstream
-- retrieval state of its cache (remote_cache). Content stays in the blob and
-- item tables; cache-only reads still use cached items.
CREATE TABLE remote_sources (
    repo_key TEXT PRIMARY KEY REFERENCES repositories (key) ON DELETE CASCADE,
    doc      TEXT NOT NULL
);

CREATE TABLE remote_cache (
    repo_key TEXT NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    cache_id TEXT NOT NULL,
    path     TEXT NOT NULL,
    doc      TEXT NOT NULL,
    PRIMARY KEY (repo_key, cache_id)
);

CREATE TABLE gitlfs_locks (
    id        TEXT COLLATE "C" PRIMARY KEY,
    repo_key  TEXT COLLATE "C" NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    path      TEXT COLLATE "C" NOT NULL,
    owner     TEXT NOT NULL,
    locked_at BIGINT NOT NULL,
    UNIQUE (repo_key, path)
);
CREATE INDEX gitlfs_locks_repo_path ON gitlfs_locks (repo_key, path);

CREATE TABLE bower_registrations (
    repo_key TEXT NOT NULL REFERENCES repositories (key) ON DELETE CASCADE,
    name     TEXT NOT NULL,
    url      TEXT NOT NULL,
    PRIMARY KEY (repo_key, name)
);
