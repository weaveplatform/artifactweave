package openapibundle

import (
	"os"
	"path/filepath"
	"strings"
	"testing"

	"gopkg.in/yaml.v3"
)

func write(t *testing.T, dir, name, body string) {
	t.Helper()
	if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
}

const info = `openapi: 3.0.3
info:
  title: t
  version: "1"
servers:
  - url: /svc
tags:
  - name: a
`

func TestUnitBundleMergesAndSorts(t *testing.T) {
	dir := t.TempDir()
	write(t, dir, "info.yaml", info)
	write(
		t,
		dir,
		"paths-zeta.yaml",
		"paths:\n  /z:\n    get:\n      operationId: z\n      responses:\n        \"200\":\n          description: ok\ncomponents:\n  schemas:\n    Zed:\n      type: string\n",
	)
	write(
		t,
		dir,
		"paths-alpha.yaml",
		"paths:\n  /a:\n    get:\n      operationId: a\n      responses:\n        \"200\":\n          description: ok\n",
	)
	write(
		t,
		dir,
		"components-common.yaml",
		"components:\n  schemas:\n    Alpha:\n      type: string\n  parameters:\n    p:\n      name: p\n      in: query\n      schema:\n        type: string\n",
	)
	write(t, dir, "README.md", "ignored")
	write(t, dir, "notes.yaml", "ignored: true\n")
	out, err := Bundle(dir)
	if err != nil {
		t.Fatal(err)
	}
	text := string(out)
	if !strings.HasPrefix(text, "# Generated by `make bundle`") {
		t.Fatalf("missing header:\n%s", text)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(out, &doc); err != nil {
		t.Fatal(err)
	}
	keys := make([]string, 0)
	var ordered yaml.Node
	if err := yaml.Unmarshal(out, &ordered); err != nil {
		t.Fatal(err)
	}
	root := ordered.Content[0]
	for i := 0; i < len(root.Content); i += 2 {
		keys = append(keys, root.Content[i].Value)
	}
	if strings.Join(keys, ",") != "openapi,info,servers,tags,paths,components" {
		t.Fatalf("top-level order %v", keys)
	}
	paths := lookup(root, "paths")
	if paths.Content[0].Value != "/a" || paths.Content[2].Value != "/z" {
		t.Fatalf("paths not sorted: %s", paths.Content[0].Value)
	}
	schemas := lookup(lookup(root, "components"), "schemas")
	if schemas.Content[0].Value != "Alpha" || schemas.Content[2].Value != "Zed" {
		t.Fatalf("schemas not sorted")
	}
	if lookup(lookup(root, "components"), "parameters") == nil {
		t.Fatal("parameters section lost")
	}
	if _, ok := doc["ignored"]; ok {
		t.Fatal("stray yaml file was merged")
	}
}

func TestUnitBundleErrors(t *testing.T) {
	cases := map[string]map[string]string{
		"no info":       {"paths-a.yaml": "paths: {}\n"},
		"bad info keys": {"info.yaml": "paths: {}\n"},
		"not mapping":   {"info.yaml": "- a\n"},
		"bad fragment":  {"info.yaml": info, "paths-a.yaml": "servers: []\n"},
		"dup path": {
			"info.yaml":    info,
			"paths-a.yaml": "paths:\n  /x:\n    get: {operationId: a}\n",
			"paths-b.yaml": "paths:\n  /x:\n    get: {operationId: b}\n",
		},
		"dup op id": {
			"info.yaml":    info,
			"paths-a.yaml": "paths:\n  /x:\n    get: {operationId: a}\n",
			"paths-b.yaml": "paths:\n  /y:\n    get: {operationId: a}\n",
		},
		"dup component": {
			"info.yaml":         info,
			"components-a.yaml": "components:\n  schemas:\n    S: {type: string}\n",
			"components-b.yaml": "components:\n  schemas:\n    S: {type: string}\n",
		},
		"unparsable":      {"info.yaml": info, "paths-a.yaml": "paths: [\n"},
		"empty fragments": {"info.yaml": info, "paths-a.yaml": ""},
	}
	for name, files := range cases {
		t.Run(name, func(t *testing.T) {
			dir := t.TempDir()
			for n, body := range files {
				write(t, dir, n, body)
			}
			_, err := Bundle(dir)
			if name == "empty fragments" {
				if err != nil {
					t.Fatalf("empty fragment should bundle: %v", err)
				}
				return
			}
			if err == nil {
				t.Fatal("expected an error")
			}
		})
	}
	if _, err := Bundle(filepath.Join(t.TempDir(), "missing")); err == nil {
		t.Fatal("expected error for a missing directory")
	}
}

func TestUnitBundleAll(t *testing.T) {
	root := t.TempDir()
	src := filepath.Join(root, "src")
	for _, svc := range []string{"one", "two"} {
		if err := os.MkdirAll(filepath.Join(src, svc), 0o750); err != nil {
			t.Fatal(err)
		}
		write(t, filepath.Join(src, svc), "info.yaml", info)
	}
	write(t, src, "stray.txt", "x")
	out := filepath.Join(root, "out")
	if err := os.MkdirAll(out, 0o750); err != nil {
		t.Fatal(err)
	}
	done, err := BundleAll(src, out)
	if err != nil {
		t.Fatal(err)
	}
	if strings.Join(done, ",") != "one,two" {
		t.Fatalf("bundled %v", done)
	}
	if _, err := os.Stat(filepath.Join(out, "one.openapi.yaml")); err != nil {
		t.Fatal(err)
	}
	if _, err := BundleAll(filepath.Join(root, "missing"), out); err == nil {
		t.Fatal("expected error for missing src")
	}
	if _, err := BundleAll(src, filepath.Join(root, "nowhere")); err == nil {
		t.Fatal("expected write error")
	}
	bad := filepath.Join(root, "bad")
	if err := os.MkdirAll(filepath.Join(bad, "svc"), 0o750); err != nil {
		t.Fatal(err)
	}
	if _, err := BundleAll(bad, out); err == nil {
		t.Fatal("expected error for a service without info.yaml")
	}
}
